#!/usr/bin/env python3
"""Build the result tables from EuroEval's raw records.

Reads one EuroEval results file (one JSON record per model x dataset cell, each holding
the 10 per-iteration scores) and writes:
    <out>/results.md                  all tables
    <out>/scores_per_iteration.csv    one row per model x dataset x iteration

Usage:
    python analyze.py                                   # shipped data -> results/
    python analyze.py --data out/euroeval_benchmark_results.jsonl --out out/results
"""
import argparse
import csv
import json
import os

import numpy as np
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))

SIZES = {  # size -> (safe model, abliterated model)
    "XS": ("Qwen3.5-4B-Q6_K", "Qwen3.5-4B-Uncensored-HauhauCS-Aggressive-Q6_K"),
    "S": ("Qwen3.5-9B-Q6_K", "Qwen3.5-9B-Uncensored-HauhauCS-Aggressive-Q6_K"),
    "M": ("Qwen3.5-35B-A3B-Q6_K", "Qwen3.5-35B-A3B-Uncensored-HauhauCS-Aggressive-Q6_K"),
}
METRIC = {  # dataset -> primary metric (key in EuroEval's raw results)
    "nrk-quiz-qa": "accuracy",
    "mmlu-no": "accuracy",
    "multi-ifeval-nb": "instruction_accuracy",
    "norquad": "f1",
    "mmlu": "accuracy",
    "arc": "accuracy",
    "zebra-puzzles-hard-en": "cell_wise_accuracy",
}
DATASETS = list(METRIC)
NO_SIZE_STEP = {"zebra-puzzles-hard-en"}  # size barely changes the score; ratio meaningless


def load(path):
    """(model, dataset) -> per-iteration scores in percent. Later records win."""
    cells = {}
    for line in open(path):
        if not line.strip():
            continue
        rec = json.loads(line)
        details = rec["eval_library"]["additional_details"]
        dataset = details["dataset"]
        raw = details["raw_results"]
        raw = json.loads(raw) if isinstance(raw, str) else raw
        scores = np.array([r[METRIC[dataset]] for r in raw], dtype=float)
        if scores.max() <= 1.0:
            scores *= 100
        cells[(rec["model_info"]["id"], dataset)] = scores
    return cells


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(x) for x in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


def ci95(x):
    half = stats.t.ppf(0.975, len(x) - 1) * x.std(ddof=1) / np.sqrt(len(x))
    return x.mean() - half, x.mean() + half


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=os.path.join(HERE, "data", "euroeval_results.jsonl"))
    ap.add_argument("--zebra-unpatched",
                    default=os.path.join(HERE, "data", "euroeval_results_zebra_unpatched.jsonl"))
    ap.add_argument("--out", default=os.path.join(HERE, "results"))
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)

    cells = load(args.data)
    missing = [(m, d) for d in DATASETS for pair in SIZES.values() for m in pair
               if (m, d) not in cells]
    if missing:
        raise SystemExit(f"missing cells: {missing}")
    mean = {k: v.mean() for k, v in cells.items()}

    with open(os.path.join(args.out, "scores_per_iteration.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["size", "condition", "model", "dataset", "metric", "iteration", "score"])
        for d in DATASETS:
            for size, pair in SIZES.items():
                for cond, m in zip(("safe", "abliterated"), pair):
                    for i, s in enumerate(cells[(m, d)]):
                        w.writerow([size, cond, m, d, METRIC[d], i, round(s, 4)])

    md = ["# Results\n",
          f"Generated by `analyze.py` from `{os.path.relpath(args.data, HERE)}`. Scores are "
          "means over 10 bootstrap iterations, in percent. Difference = abliterated − safe, "
          "in percentage points (pp).\n"]

    # Per-pair differences
    rows, diffs, ratios = [], {s: [] for s in SIZES}, []
    for d in DATASETS:
        safe = {s: mean[(SIZES[s][0], d)] for s in SIZES}
        step = np.mean([safe["S"] - safe["XS"], safe["M"] - safe["S"]])
        row = [d, METRIC[d]]
        for s, (ms, ma) in SIZES.items():
            diff = mean[(ma, d)] - mean[(ms, d)]
            diffs[s].append(diff)
            row.append(f"{mean[(ms, d)]:.1f} / {mean[(ma, d)]:.1f} ({diff:+.1f})")
            if d not in NO_SIZE_STEP:
                ratios.append(abs(diff) / step)
        row.append("–" if d in NO_SIZE_STEP else f"{step:.1f}")
        rows.append(row)
    md.append("## Safe vs abliterated, per dataset\n")
    md.append("Cells: safe / abliterated (difference). Mean size step = mean of (S − XS) and "
              "(M − S) for the safe models.\n")
    md.append(table(["dataset", "metric", "XS", "S", "M", "mean size step"], rows))

    # Pooled
    all_d = np.concatenate([np.array(v) for v in diffs.values()])
    prow = []
    for name, x in [("all pairs", all_d)] + [(s, np.array(v)) for s, v in diffs.items()]:
        lo, hi = ci95(x)
        prow.append([f"{name} ({len(x)})", f"{x.mean():+.2f}", f"{lo:+.2f} to {hi:+.2f}",
                     f"{x.min():+.1f} to {x.max():+.1f}", f"{(x < 0).sum()} / {len(x)}"])
    md.append("\n## Pooled difference\n")
    md.append("Mean of the per-dataset differences; 95% CI from their spread (t-distribution).\n")
    md.append(table(["pairs", "mean diff (pp)", "95% CI", "range", "negative"], prow))
    neg = int((all_d < 0).sum())
    p_sign = stats.binomtest(neg, len(all_d), 0.5).pvalue
    ratios = np.array(ratios)
    md.append(f"\nSign test (two-sided): {neg}/{len(all_d)} negative, p = {p_sign:.3f}.\n")
    md.append(f"\n|difference| / mean size step, {len(ratios)} pairs without zebra: "
              f"{(ratios < 1 / 3).sum()} under 1/3, {(ratios < 0.5).sum()} under 1/2, "
              f"max {ratios.max():.2f}.\n")

    # Size gaps for scale
    grow = [[d, f"{mean[(SIZES['S'][0], d)] - mean[(SIZES['XS'][0], d)]:+.1f}",
             f"{mean[(SIZES['M'][0], d)] - mean[(SIZES['S'][0], d)]:+.1f}",
             f"{mean[(SIZES['M'][0], d)] - mean[(SIZES['XS'][0], d)]:+.1f}"] for d in DATASETS]
    md.append("\n## Size gaps (safe models), for scale\n")
    md.append(table(["dataset", "XS → S", "S → M", "XS → M"], grow))

    # Per-pair noise
    nrow = []
    for d in DATASETS:
        row = [d]
        for s, (ms, ma) in SIZES.items():
            dd = cells[(ma, d)] - cells[(ms, d)]
            flag = " *" if abs(dd.mean()) > 1.96 * dd.std(ddof=1) else ""
            row.append(f"{dd.std(ddof=1):.2f}{flag}")
        nrow.append(row)
    md.append("\n## Noise per pair\n")
    md.append("SD of the 10 paired iteration differences (pp). Iteration i uses the same "
              "bootstrap sample of items for every model, so this is the bootstrap standard "
              "error of the pair's difference. * = |difference| > 1.96 × SD.\n")
    md.append(table(["dataset", "XS", "S", "M"], nrow))

    # Zebra with and without JSON enforcement
    if os.path.exists(args.zebra_unpatched):
        z = load(args.zebra_unpatched)
        d = "zebra-puzzles-hard-en"
        zrow = []
        for label, src in [("json_object (EuroEval default, not enforced)", z),
                           ("json_schema (enforced, used above)", cells)]:
            zrow.append([label] + [f"{src[(ms, d)].mean():.1f} / {src[(ma, d)].mean():.1f}"
                                   for ms, ma in SIZES.values()])
        md.append("\n## zebra-puzzles-hard-en with and without enforced JSON output\n")
        md.append("Cell-wise accuracy, safe / abliterated.\n")
        md.append(table(["response format", "XS", "S", "M"], zrow))

    text = "\n".join(md)
    with open(os.path.join(args.out, "results.md"), "w") as f:
        f.write(text)
    print(text)


if __name__ == "__main__":
    main()
